const DICT: Record<Lang, Record<TKey, string>> = { en, hi, mr };

export type TVars = Record<string, string | number>;

export function translate(lang: Lang, key: TKey, vars?: TVars): string {
  let s = DICT[lang][key] ?? en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

export function pick(text: L10n | undefined, lang: Lang): string {
  if (!text) return "";
  return text[lang] || text.en;
}

export function speechCode(lang: Lang): string {
  return LANGS.find((l) => l.id === lang)?.speech ?? "en-IN";
}
